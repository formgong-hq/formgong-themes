"""Make assets/marrow.css from the Marrow HTML release (index.html, inline <style>).

Every class gets the mw- prefix (so nothing collides with theme.css / stilla.css, which still style cart, search and
the product pages), element rules are scoped to Marrow's own blocks, and the photo/colour values that a merchant can
change come from theme settings (CSS variables set in layout/theme.liquid).

Usage: python3 scripts/build_css.py <marrow html dir> <theme dir>
"""
import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1]) / "index.html"
OUT = Path(sys.argv[2]) / "assets/marrow.css"
S = ':where([class^="mw-"],[class*=" mw-"])'
html = SRC.read_text()
css = re.search(r"<style>\n(.*?)</style>", html, re.S).group(1)
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def prefix_classes(sel):
    return re.sub(r"\.(?=[A-Za-z_-])([\w-]+)", r".mw-\1", sel)


ELEMENTS = {"*", "*::before", "*::after", "img", "svg", "canvas", "a", "button", "input", "select", "textarea", "ul"}


def fix_selector(sel):
    sel = sel.strip()
    if sel in ELEMENTS:  # global element resets: only inside Marrow blocks (and on Marrow elements themselves)
        if sel.startswith("*"):
            pseudo = sel[1:]
            return f"{S}{pseudo}, {S} *{pseudo}"
        return f"{S} {sel}, {sel}{S}"
    if sel == "main":
        return None
    sel = prefix_classes(sel)
    sel = re.sub(r"^footer\b", ".mw-footer", sel)
    if not sel.startswith("html:has"):
        sel = re.sub(r"(?<![\w(.-])dialog(?=[\[:{\s]|$)", "dialog.mw-dialog", sel)
    # state classes on <html>: mwr- (not mw-), so the page root never counts as a Marrow block for the resets
    return re.sub(r"\.mw-(js|motion|solid|menu-open|pet-cat|has-cursor)\b", r".mwr-\1", sel)


def convert(block):
    out = []
    i = 0
    while i < len(block):
        j = block.find("{", i)
        if j < 0:
            break
        head = block[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(block[k], 0)
            k += 1
        body = block[j + 1:k - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            out.append(f"{head} {{\n{convert(body)}}}\n")
        elif head.startswith("@keyframes"):
            out.append(f"{head.replace('@keyframes ', '@keyframes mw-')} {{{body}}}\n")
        else:
            sels = [fix_selector(s) for s in head.split(",")]
            sels = [s for s in sels if s]
            if sels:
                body = re.sub(r"\banimation:\s*(\w+)", lambda m: f"animation: mw-{m.group(1)}" if m.group(1) not in ("none",) else m.group(0), body)
                out.append(f"{', '.join(sels)} {{{body}}}\n")
        i = k
    return "".join(out)


out = convert(css)
# Theme settings: colours of the scheme and the photo of the banner section.
out = out.replace('url("img/cta-dog.webp")', "var(--mw-cta-img, none)")
for name, val in {"--ink": "var(--color-text, #1c2a6b)", "--accent": "var(--color-accent, #ff6b2c)",
                  "--mist": "var(--color-surface, #eef2fb)", "--line": "var(--color-border, #d6dcef)"}.items():
    out, n = re.subn(rf"(\n\s*|{{\s*){name}: #[0-9a-f]+;", rf"\g<1>{name}: {val};", out, count=1)
    assert n == 1, name
for name in ("--hero", "--accent-dark", "--cream", "--ink-2"):
    out, n = re.subn(rf"{name}: (#[0-9a-f]+);", rf"{name}: var(--mw{name[1:]}, \1);", out, count=1)
    assert n == 1, name
assert "img/" not in out

